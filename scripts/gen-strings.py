SKIP = re.compile(r"^(|[a-z0-9_.\-]+|[A-Z][a-zA-Z]+ID|.*\.(json|png)|https?:.*|--.*|main|root|Glass|QuietDeck|Steam Deck|microSD|SteamGridDB|BIOS|Add Deck|steamdeck.*|CPU|GPU|CFBundleShortVersionString|QuietDeck/covers|sudo systemctl enable --now sshd|passwd|yyyy-MM-dd HH-mm|SteamOS .*|\s*|%@ · %@|%@%%|%@, %@|%@ \(%@\)|%.0f °C|GPU %.0f °C|–|\\n)$")

def swift_key(lit):
    return re.sub(r"\\\(([^()]|\([^()]*\))*\)", lambda m: "%lld" if re.search(r"count|percent|battery|\.index|updateCount|activeCount", m.group(0)) and "name" not in m.group(0) else "%@", lit)

found = set()
for f in glob.glob("App/Sources/*.swift"):
    if f.endswith(("PressKit.swift", "Keychain.swift")):
        continue
    src = open(f).read()
    for line in src.split("\n"):
        if line.strip().startswith("//") or "verbatim:" in line and line.count('"') <= 2:
            continue
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', line):
            found.add(swift_key(m.group(1)))
missing = sorted(k for k in found if not SKIP.match(k) and k not in PT and " " in k or (k[:1].isupper() and k not in PT and not SKIP.match(k)))

strings = {k: {"localizations": {"pt-BR": {"stringUnit": {"state": "translated", "value": v}}}} for k, v in sorted(PT.items())}

def plural(key, en_one, pt_one):
    forms = lambda one, other: {"variations": {"plural": {"one": {"stringUnit": {"state": "translated", "value": one}}, "other": {"stringUnit": {"state": "translated", "value": other}}}}}
    strings[key] = {"localizations": {"en": forms(en_one, key), "pt-BR": forms(pt_one, PT[key])}}

plural("%lld updates", "%lld update", "%lld atualização")
plural("Send %lld Games", "Send %lld Game", "Enviar %lld jogo")
json.dump({"sourceLanguage": "en", "strings": strings, "version": "1.0"}, open("App/Resources/Localizable.xcstrings", "w"), ensure_ascii=False, indent=1)
print(len(PT), "traduções")
